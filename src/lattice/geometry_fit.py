"""Extract promoter geometry from an H3K27me3 profile, and map it to lattice
parameters.

Designed to run identically on (a) synthetic profiles generated by the lattice,
so the inversion can be round-trip validated, and (b) real binned ChIP coverage
once profile-resolution data exists.

FEATURES (all scale-free except the plateaus, so normalisation does not matter):
  core_up, core_dn   half-max crossing distance from the TSS, per side  (bp)
  rise_up, rise_dn   20-80% rise width of the boundary, per side        (bp)
  plateau_up/dn      occupancy of the flanking domain, per side
  dip                plateau - core occupancy
These are the numbers the lattice's Geometry and antagonist profiles map onto.
"""
import numpy as np

FEATURES = ['core_up', 'core_dn', 'rise_up', 'rise_dn', 'plateau_up', 'plateau_dn', 'dip']


def _side(x, y, sign, plateau_q=75, smooth=3):
    """Features for one side. sign=+1 downstream, -1 upstream."""
    m = (sign * x) > 0
    xs, ys = np.abs(x[m]), y[m]
    o = np.argsort(xs); xs, ys = xs[o], ys[o]
    if smooth > 1 and len(ys) > smooth:
        k = np.ones(smooth) / smooth
        ys = np.convolve(ys, k, mode='same')
    if len(xs) < 5:
        return np.nan, np.nan, np.nan
    far = xs > np.percentile(xs, 50)
    plateau = float(np.percentile(ys[far], plateau_q)) if far.any() else float(ys.max())
    core = float(np.min(ys[:max(2, len(ys) // 10)]))
    if plateau - core < 0.02:
        return np.nan, np.nan, plateau            # no resolvable boundary
    def cross(frac):
        t = core + frac * (plateau - core)
        i = np.where(ys >= t)[0]
        if not len(i):
            return np.nan
        j = i[0]
        if j == 0:
            return float(xs[0])
        x0, x1, y0, y1 = xs[j - 1], xs[j], ys[j - 1], ys[j]
        return float(x0 + (t - y0) * (x1 - x0) / (y1 - y0)) if y1 != y0 else float(x1)
    half = cross(0.5)
    rise = cross(0.8) - cross(0.2)
    return half, rise, plateau


def profile_features(x, y):
    """x in bp relative to TSS (negative = upstream), y = occupancy."""
    x, y = np.asarray(x, float), np.asarray(y, float)
    cu, ru, pu = _side(x, y, -1)
    cd, rd, pd = _side(x, y, +1)
    core_mask = np.abs(x) < 300
    core_val = float(y[core_mask].mean()) if core_mask.any() else float(y[np.argmin(np.abs(x))])
    plat = np.nanmean([pu, pd])
    return dict(core_up=cu, core_dn=cd, rise_up=ru, rise_dn=rd,
                plateau_up=pu, plateau_dn=pd, dip=plat - core_val)


def features_vector(f):
    return np.array([f[k] for k in FEATURES], float)


def lattice_geometry_from_features(f, pitch=190.0, pad=3.0):
    """Turn measured geometry into a lattice Geometry (sizes only)."""
    from promoter_lattice import Geometry
    cu = f['core_up'] if np.isfinite(f['core_up']) else 500.0
    cd = f['core_dn'] if np.isfinite(f['core_dn']) else 900.0
    return Geometry(pitch=pitch,
                    up_bp=float(max(1500.0, pad * cu)),
                    dn_bp=float(max(4000.0, pad * cd + 4000.0)),
                    core_up_bp=float(cu), core_dn_bp=float(cd),
                    cgi_sigma_bp=float(max(150.0, 0.5 * min(cu, cd))),
                    body_start_bp=float(0.3 * cd))


def n_nucleosomes(f, pitch=190.0):
    g = lattice_geometry_from_features(f, pitch)
    return dict(N_core=int(round((g.core_up_bp + g.core_dn_bp) / pitch)),
                N_up=int(round(g.up_bp / pitch)),
                N_dn=int(round(g.dn_bp / pitch)))
